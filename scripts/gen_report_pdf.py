class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            # Displayed body numbering = physical page - 1 (TOC page is roman i)
            self.notify('TOCEntry', (level, text, self.page - 1, key))


def add_heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


MAX_KEEP_HEIGHT = A4[1] * 0.4

def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        try:
            _, h = el.wrap(AVAIL_W, AVAIL_H)
        except Exception:
            h = 0
        total_h += h
    if total_h <= MAX_KEEP_HEIGHT:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def make_table(spec):
    headers = spec['headers']
    rows = spec['rows']
    ratios = spec['ratios']
    aligns = spec.get('aligns', ['left'] * len(headers))
    col_widths = [r * AVAIL_W * 0.98 for r in ratios]
    assert sum(col_widths) <= AVAIL_W + 0.5, "table overflow"
    data = [[Paragraph('<b>%s</b>' % h, cell_header) for h in headers]]
    for row in rows:
        cells = []
        for i, val in enumerate(row):
            st = cell_center if aligns[i] == 'center' else cell_style
            cells.append(Paragraph(str(val), st))
        data.append(cells)
    tbl = Table(data, colWidths=col_widths, hAlign='CENTER', repeatRows=1)
    style_cmds = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for ri in range(1, len(data)):
        style_cmds.append(('BACKGROUND', (0, ri), (-1, ri),
                           TABLE_ROW_EVEN if ri % 2 == 1 else TABLE_ROW_ODD))
    tbl.setStyle(TableStyle(style_cmds))
    flow = [Spacer(1, 18)]
    _, th = tbl.wrap(AVAIL_W, AVAIL_H)
    if th <= MAX_KEEP_HEIGHT:
        flow.append(KeepTogether([tbl]))
    else:
        flow.append(tbl)
    flow.append(Spacer(1, 6))
    flow.append(Paragraph(spec['caption'], caption_style))
    flow.append(Spacer(1, 12))
    return flow, th


def make_callout(stats):
    n = len(stats)
    gap = 12
    box_w = (AVAIL_W * 0.98 - gap * (n - 1)) / n
    col_widths, val_row, lab_row = [], [], []
    for idx, (value, label) in enumerate(stats):
        col_widths.append(box_w)
        val_row.append(Paragraph('<b>%s</b>' % value, stat_style))
        lab_row.append(Paragraph(label, stat_label_style))
        if idx < n - 1:
            col_widths.append(gap)
            val_row.append('')
            lab_row.append('')
    row = Table([val_row, lab_row], colWidths=col_widths, hAlign='CENTER')
    style_cmds = [
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, 0), 9),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
        ('TOPPADDING', (0, 1), (-1, 1), 2),
        ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
        ('LEFTPADDING', (0, 0), (-1, -1), 2),
        ('RIGHTPADDING', (0, 0), (-1, -1), 2),
    ]
    for k in range(n):
        c = k * 2
        style_cmds.append(('BACKGROUND', (c, 0), (c, 1), CARD_BG))
    # Single enclosing frame + internal vertical dividers → one symmetric block
    style_cmds.append(('BOX', (0, 0), (-1, 1), 1, ACCENT))
    for k in range(n - 1):
        c = k * 2 + 1
        style_cmds.append(('LINEBEFORE', (c, 0), (c, 1), 1, ACCENT))
    row.setStyle(TableStyle(style_cmds))
    return [Spacer(1, 10), KeepTogether([row]), Spacer(1, 14)]


def make_chart(spec):
    from PIL import Image as PILImage
    pil = PILImage.open(spec['path'])
    ow, oh = pil.size
    max_w, max_h = AVAIL_W * 0.96, 290
    ratio = min(max_w / ow if ow > max_w else 1.0, max_h / oh if oh > max_h else 1.0)
    img = Image(spec['path'], width=ow * ratio, height=oh * ratio)
    out = safe_keep_together([img, Paragraph(spec['caption'], caption_style)])
    return [Spacer(1, 16)] + out + [Spacer(1, 14)]


def table_height_estimate(spec):
    ratios = spec['ratios']
    col_widths = [r * AVAIL_W * 0.98 for r in ratios]
    h = 24  # header row
    for row in spec['rows']:
        max_lines = 1
        for i, val in enumerate(row):
            w = col_widths[i] - 12
            text_w = stringWidth(str(val), 'FreeSerif', 9)
            import math
            max_lines = max(max_lines, math.ceil(text_w / max(w, 30)))
        h += max_lines * 12.5 + 10
    return h


