def render_flowables():
    story = []
    # ── TOC (front matter, roman i) ──
    story.append(Paragraph('<b>Table des matières</b>', toc_title_style))
    toc = TableOfContents()
    toc.levelStyles = [
        ParagraphStyle('TOC0', fontName='FreeSerif', fontSize=11.5, leading=20,
                       leftIndent=6, textColor=TEXT_PRIMARY),
        ParagraphStyle('TOC1', fontName='FreeSerif', fontSize=10.5, leading=17,
                       leftIndent=26, textColor=TEXT_MUTED),
    ]
    story.append(toc)
    story.append(PageBreak())  # structural break: TOC → content

    i = 0
    n = len(BLOCKS)
    while i < n:
        block = BLOCKS[i]
        t = block[0]
        if t in ('h1', 'h2'):
            level = 0 if t == 'h1' else 1
            style = h1_style if t == 'h1' else h2_style
            heading = add_heading(block[1], style, level=level)
            rule = HRFlowable(width='100%', thickness=1.2 if t == 'h1' else 0.8,
                              color=ACCENT if t == 'h1' else BORDER,
                              spaceBefore=0, spaceAfter=10 if t == 'h1' else 8)
            # Look-ahead: require room for heading + next table/chart
            required = 90
            if i + 1 < n and BLOCKS[i + 1][0] == 'table':
                required = 70 + table_height_estimate(BLOCKS[i + 1][1]) + 40
            story.append(CondPageBreak(min(required, AVAIL_H * 0.92)))
            story.extend(safe_keep_together([heading, rule]))
            i += 1
            continue
        if t == 'body':
            story.append(Paragraph(block[1], body_style))
        elif t == 'num':
            for k, item in enumerate(block[1], 1):
                story.append(Paragraph('<b>%d.</b>  %s' % (k, item), bullet_style))
            story.append(Spacer(1, 6))
        elif t == 'table':
            flow, _ = make_table(block[1])
            story.extend(flow)
        elif t == 'callout':
            story.extend(make_callout(block[1]['stats']))
        elif t == 'chart':
            block[1]['path'] = os.path.join(CONTENT_DIR, block[1]['path'])
            story.extend(make_chart(block[1]))
        i += 1
    return story


def on_page(canvas, doc):
    canvas.saveState()
    # header: title left + accent rule
    canvas.setFont('FreeSerif', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 40, DOC_TITLE)
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 46, PAGE_W - MARGIN, PAGE_H - 46)
    # footer: light rule + author left + page number right
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 44, PAGE_W - MARGIN, 44)
    canvas.setFont('FreeSerif', 7.5)
    canvas.drawString(MARGIN, 32, 'assihervey-coder · YAHRIA CODE OS')
    page_label = 'i' if doc.page == 1 else str(doc.page - 1)
    canvas.drawRightString(PAGE_W - MARGIN, 32, page_label)
    canvas.restoreState()


def main():
    build_chart_png()
    doc = TocDocTemplate(
        OUT_BODY, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN, topMargin=64, bottomMargin=64,
        title=DOC_TITLE, author='Z.ai', creator='Z.ai',
        subject="Analyse constitutionnelle du corpus YAHRIA — forces, défauts, évaluation et corrections",
    )
    story = render_flowables()
    doc.multiBuild(story, onFirstPage=on_page, onLaterPages=on_page)
    print("body OK:", OUT_BODY)

    # ── Merge cover as page 0 ──
    from pypdf import PdfReader, PdfWriter
    A4_W, A4_H = 595.28, 841.89

    def normalize(page):
        w, h = float(page.mediabox.width), float(page.mediabox.height)
        if abs(w - A4_W) > 0.1 or abs(h - A4_H) > 0.1:
            page.scale_to(A4_W, A4_H)
        return page

    writer = PdfWriter()
    writer.add_page(normalize(PdfReader(COVER_PDF).pages[0]))
    for page in PdfReader(OUT_BODY).pages:
        writer.add_page(normalize(page))
    writer.add_metadata({
        '/Title': DOC_TITLE, '/Author': 'Z.ai', '/Creator': 'Z.ai',
        '/Subject': "Analyse constitutionnelle du corpus YAHRIA — forces, défauts, évaluation et corrections",
    })
    os.makedirs(os.path.dirname(OUT_FINAL), exist_ok=True)
    with open(OUT_FINAL, 'wb') as f:
        writer.write(f)
    print("final OK:", OUT_FINAL)


if __name__ == '__main__':
    main()
